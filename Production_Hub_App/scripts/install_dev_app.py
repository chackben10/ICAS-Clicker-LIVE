"""Install /Applications/Production Hub Dev.app: open the staging build from Finder.

    /Library/Frameworks/Python.framework/Versions/3.12/bin/python3 \
        Production_Hub_App/scripts/install_dev_app.py

The installed app is a launcher, not a copy of the code. Opening it runs this
checkout's source (Production_Hub_App/main.py, which relaunches through the
stable `.build/dev/Production Hub Dev.app` identity)
in a Terminal window that shows the log. Source edits need no reinstall; run
this again only if the checkout moves or the Python install changes.

The installed release (`Production Hub.app`) and Dev share a single-instance
lock and the same settings, so the launcher offers to quit the release first.
"""

from __future__ import annotations

import argparse
import plistlib
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

APP_NAME = "Production Hub Dev"
LAUNCHER_BUNDLE_ID = "org.icas.productionhub.dev.launcher"
RELEASE_BUNDLE_ID = "org.icas.productionhub"
DEFAULT_PYTHON = Path("/Library/Frameworks/Python.framework/Versions/3.12/bin/python3")
APP_ROOT = Path(__file__).resolve().parents[1]
REPOSITORY = APP_ROOT.parent


def _quote(value: str) -> str:
    return "'" + value.replace("'", "'\"'\"'") + "'"


def launcher_script(python: Path) -> str:
    """The app's executable: guard against a running release, then open Terminal."""

    return f"""#!/bin/zsh
# Production Hub Dev launcher (generated by Production_Hub_App/scripts/install_dev_app.py).
set -u
here="${{0:A:h}}"
command_file="$here/../Resources/Open Production Hub Dev.command"

dialog() {{
  /usr/bin/osascript -e "display dialog \\"$1\\" with title \\"{APP_NAME}\\" buttons {{\\"OK\\"}} default button \\"OK\\" with icon caution" >/dev/null 2>&1
}}

if [[ ! -f {_quote(str(APP_ROOT / "main.py"))} ]]; then
  dialog "The Dev source was not found at {REPOSITORY}. Run Production_Hub_App/scripts/install_dev_app.py from the new location."
  exit 1
fi
if [[ ! -x {_quote(str(python))} ]]; then
  dialog "Python 3.12 was not found at {python}. Reinstall it, or rerun install_dev_app.py with --python."
  exit 1
fi

# The Dev runtime (not this launcher, which shares the name).
if /usr/bin/pgrep -f ".build/dev/Production Hub Dev.app/Contents/MacOS/Production Hub Dev" >/dev/null; then
  dialog "Production Hub Dev is already running."
  exit 0
fi

if /usr/bin/pgrep -f "Production Hub.app/Contents/MacOS/Production Hub" >/dev/null; then
  answer=$(/usr/bin/osascript -e 'display dialog "Production Hub (the live app) is running. Dev cannot run at the same time.\\n\\nQuit the live app and open Dev? Only do this when no service is running." with title "{APP_NAME}" buttons {{"Cancel", "Quit Live and Open Dev"}} default button "Cancel" with icon caution' -e 'button returned of result' 2>/dev/null)
  if [[ "$answer" != "Quit Live and Open Dev" ]]; then
    exit 0
  fi
  /usr/bin/osascript -e 'tell application id "{RELEASE_BUNDLE_ID}" to quit' >/dev/null 2>&1
  for _ in {{1..40}}; do
    /usr/bin/pgrep -f "Production Hub.app/Contents/MacOS/Production Hub" >/dev/null || break
    sleep 0.5
  done
  if /usr/bin/pgrep -f "Production Hub.app/Contents/MacOS/Production Hub" >/dev/null; then
    dialog "The live app did not quit. Quit it from its menu, then open Dev again."
    exit 1
  fi
fi

exec /usr/bin/open -a Terminal "$command_file"
"""


def command_script(python: Path) -> str:
    """What Terminal runs: the source entry point, with the log in the window."""

    return f"""#!/bin/zsh
# Production Hub Dev (generated by Production_Hub_App/scripts/install_dev_app.py).
# Keep this window open while Dev runs; closing it quits Dev.
cd {_quote(str(REPOSITORY))} || exit 1
printf '\\033]0;{APP_NAME}\\007'
echo "Production Hub Dev: {REPOSITORY} "
{_quote(str(python))} Production_Hub_App/main.py "$@"
exit_code=$?
echo
echo "Production Hub Dev exited with status $exit_code. You can close this window."
exit $exit_code
"""


def build(destination: Path, python: Path) -> Path:
    app = destination / f"{APP_NAME}.app"
    with tempfile.TemporaryDirectory() as scratch:
        staged = Path(scratch) / f"{APP_NAME}.app"
        macos = staged / "Contents" / "MacOS"
        resources = staged / "Contents" / "Resources"
        macos.mkdir(parents=True)
        resources.mkdir(parents=True)
        executable = macos / APP_NAME
        executable.write_text(launcher_script(python), encoding="utf-8")
        executable.chmod(0o755)
        command = resources / "Open Production Hub Dev.command"
        command.write_text(command_script(python), encoding="utf-8")
        command.chmod(0o755)
        icon = APP_ROOT / "assets" / "ProductionHub.icns"
        if icon.is_file():
            shutil.copy2(icon, resources / "ProductionHub.icns")
        info = {
            "CFBundleName": APP_NAME,
            "CFBundleDisplayName": APP_NAME,
            "CFBundleExecutable": APP_NAME,
            "CFBundleIdentifier": LAUNCHER_BUNDLE_ID,
            "CFBundlePackageType": "APPL",
            "CFBundleShortVersionString": "1.0",
            "CFBundleVersion": "1",
            "CFBundleIconFile": "ProductionHub",
            "LSUIElement": True,  # a launcher: no Dock icon of its own
            "NSHighResolutionCapable": True,
        }
        with (staged / "Contents" / "Info.plist").open("wb") as handle:
            plistlib.dump(info, handle)
        subprocess.run(["/usr/bin/codesign", "--force", "--sign", "-", str(staged)], check=True,
                       capture_output=True)
        if app.exists():
            _to_trash(app)
        shutil.move(str(staged), app)
    return app


def _to_trash(path: Path) -> None:
    """Move an old copy to the Trash (recoverable), never delete it outright."""

    trash = Path.home() / ".Trash"
    target = trash / path.name
    counter = 1
    while target.exists():
        target = trash / f"{path.stem} {counter}{path.suffix}"
        counter += 1
    shutil.move(str(path), target)
    print(f"Moved the previous {path.name} to the Trash ({target.name}).")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--destination", type=Path, default=Path("/Applications"))
    parser.add_argument("--python", type=Path, default=DEFAULT_PYTHON,
                        help="Python with the app's requirements (default: the python.org 3.12 framework)")
    args = parser.parse_args(argv)
    if not args.python.is_file():
        print(f"Python not found: {args.python}", file=sys.stderr)
        return 1
    app = build(args.destination, args.python)
    print(f"Installed {app}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
